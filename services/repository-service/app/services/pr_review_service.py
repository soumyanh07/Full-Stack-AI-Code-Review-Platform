import os
import time

import jwt
import requests
from github import Github

from app.core.config import settings
from app.services.review_service import ReviewService


class PRReviewService:
    """
    Reviews GitHub Pull Requests using the AI review service.

    Features:
    - Reviews changed files
    - Skips binary / files without patches
    - Truncates very large patches
    - Publishes a consolidated GitHub PR review comment
    - Attempts to publish a GitHub Check Run
    """

    MAX_PATCH_CHARS = 12000

    def __init__(self):
        self.github = Github(self._get_installation_token())
        self.review = ReviewService()

    def _get_installation_token(self):
        app_id = settings.GITHUB_APP_ID
        key_path = settings.GITHUB_APP_PRIVATE_KEY_PATH
        installation_id = settings.GITHUB_APP_INSTALLATION_ID

        with open(key_path, "r") as key_file:
            private_key = key_file.read()

        now = int(time.time())

        app_jwt = jwt.encode(
            {
                "iat": now - 60,
                "exp": now + 540,
                "iss": str(app_id),
            },
            private_key,
            algorithm="RS256",
        )

        response = requests.post(
            f"https://api.github.com/app/installations/{installation_id}/access_tokens",
            headers={
                "Authorization": f"Bearer {app_jwt}",
                "Accept": "application/vnd.github+json",
            },
            timeout=30,
        )

        response.raise_for_status()

        return response.json()["token"]

    def review_pull_request(
        self,
        repository: str,
        pr_number: int,
    ):
        repo = self.github.get_repo(repository)
        pr = repo.get_pull(pr_number)

        reviews = []

        # ---------------------------------------------------------
        # Review every changed file
        # ---------------------------------------------------------
        for file in pr.get_files():

            # Binary files and some generated files do not have
            # a patch available from GitHub.
            if not file.patch:
                continue

            patch = file.patch

            # Prevent very large diffs from overwhelming the LLM.
            truncated = len(patch) > self.MAX_PATCH_CHARS

            if truncated:
                patch = (
                    patch[: self.MAX_PATCH_CHARS]
                    + "\n\n"
                    "[PATCH TRUNCATED: remaining diff omitted]"
                )

            # Run AI review.
            result = self.review.review(patch)

            reviews.append(
                {
                    "file": file.filename,
                    "review": result,
                    "truncated": truncated,
                    "patch_chars": len(patch),
                }
            )

        # ---------------------------------------------------------
        # Publish results to GitHub
        # ---------------------------------------------------------
        check_run_created = False
        check_run_error = None

        if reviews:

            # =====================================================
            # 1. Create consolidated PR review comment
            # =====================================================

            body_parts = [
                "## 🤖 AI Code Review",
                "",
                "Automated review generated by the AI Code Review Platform.",
                "",
            ]

            for item in reviews:
                body_parts.extend(
                    [
                        f"### `{item['file']}`",
                        "",
                        item["review"]["review"],
                        "",
                    ]
                )

                if item["truncated"]:
                    body_parts.extend(
                        [
                            "> ⚠️ This file's patch was truncated before AI analysis.",
                            "",
                        ]
                    )

            body = "\n".join(body_parts)

            # GitHub PR review comment.
            pr.create_review(
                body=body,
                event="COMMENT",
            )

            # =====================================================
            # 2. Attempt GitHub Check Run
            # =====================================================

            try:
                summary_lines = [
                    f"Reviewed **{len(reviews)} changed file(s)**.",
                    "",
                ]

                for item in reviews:
                    status = (
                        "⚠️ truncated"
                        if item["truncated"]
                        else "✅ reviewed"
                    )

                    summary_lines.append(
                        f"- `{item['file']}` — {status}"
                    )

                summary = "\n".join(summary_lines)

                repo.create_check_run(
                    name="AI Code Review",
                    head_sha=pr.head.sha,
                    status="completed",
                    conclusion="success",
                    output={
                        "title": "AI Code Review completed",
                        "summary": summary,
                        "text": body,
                    },
                )

                check_run_created = True

            except Exception as exc:
                check_run_error = str(exc)

        return {
            "repository": repository,
            "pull_request": pr_number,
            "reviews": reviews,
            "check_run_created": check_run_created,
            "check_run_error": check_run_error,
        }
